namespace TheBeardedBear\UrssafPlateformeNumerique\Domain\Submission;

use Stringable;
use TheBeardedBear\UrssafPlateformeNumerique\Domain\Exception\InvalidValue;

/**
 * Local identifier of a submission (not an URSSAF identifier).
 */
final readonly class SubmissionId implements Stringable
{
    private const SUBJECT = 'submission_id';
    public const MAX_LENGTH = 64;

    private function __construct(private string $value) {}

    /**
     * Rejects empty values and values longer than {@see self::MAX_LENGTH} characters. The value is kept verbatim.
     *
     * @throws InvalidValue
     */
    public static function fromString(string $value): self
    {
        if ($value === '') {
            throw InvalidValue::empty(self::SUBJECT);
        }
        if (mb_strlen($value) > self::MAX_LENGTH) {
            throw InvalidValue::tooLong(self::SUBJECT, self::MAX_LENGTH);
        }

        return new self($value);
    }

    public function value(): string
    {
        return $this->value;
    }

    public function equals(self $other): bool
    {
        return $this->value === $other->value;
    }

    public function __toString(): string
    {
        return $this->value;
    }
}
